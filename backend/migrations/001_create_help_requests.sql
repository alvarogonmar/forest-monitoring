-- Run once in the Supabase SQL Editor as the project database owner.
-- The phone supplies id and created_at; received_at comes from the server.
begin;

create table public.help_requests (
    id uuid primary key,
    created_at timestamptz not null,
    received_at timestamptz not null default now(),
    latitude double precision not null,
    longitude double precision not null,
    accuracy double precision,
    location_captured_at timestamptz not null,

    constraint help_requests_latitude_valid
        check (latitude between -90 and 90),
    constraint help_requests_longitude_valid
        check (longitude between -180 and 180),
    constraint help_requests_accuracy_valid
        check (accuracy is null or (accuracy >= 0 and accuracy < 'Infinity'::double precision)),
    constraint help_requests_created_at_finite
        check (isfinite(created_at)),
    constraint help_requests_received_at_finite
        check (isfinite(received_at)),
    constraint help_requests_location_captured_at_finite
        check (isfinite(location_captured_at))
);

-- Supports the planned administrative list order and its pagination cursor.
create index help_requests_received_at_id_idx
    on public.help_requests (received_at desc, id desc);

alter table public.help_requests enable row level security;

-- Visitors and signed-in users must go through Express, which checks permissions.
-- No direct-access policies are created for anon or authenticated.
revoke all privileges on table public.help_requests
    from public, anon, authenticated, service_role;

-- Only the trusted backend receives these permissions. No update/delete in the MVP.
grant select, insert on table public.help_requests to service_role;

comment on table public.help_requests is
    'Help requests persisted by the API. Receipt does not imply human attendance.';
comment on column public.help_requests.id is
    'UUID generated by the phone and retained across retries. No server-generated default.';
comment on column public.help_requests.received_at is
    'Server receipt timestamp; used as confirmedAt only after transaction commit.';
comment on column public.help_requests.accuracy is
    'GPS accuracy in metres; null means unavailable.';

commit;
